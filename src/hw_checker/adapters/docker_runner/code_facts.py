"""Reads the names declared in student C# code, as text, for the naming-convention checks.

The checks layer may not read files or import adapters, so, like the route table, the names
are extracted here during prepare and recorded on `ExecutionResult.code_facts`. Comments and
string contents are blanked first, so nothing in them is taken for a declaration. Names a
student cannot choose freely are left out: generated, designer and migration files,
`override` members, explicit interface implementations, constructors and operators.
Student code is never compiled or executed.
"""

import bisect
import re
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path

from hw_checker.adapters.docker_runner.csharp_source import mask_source, source_files
from hw_checker.domain import CodeFacts, FileFact, MemberFact, TypeFact, TypeKind
from hw_checker.domain.execution import MAX_CODE_FACTS

EXCLUDED_FOLDERS = frozenset({"properties", "migrations"})
GENERATED_SUFFIXES = (".designer.cs", ".g.cs", ".g.i.cs")
_AUTO_GENERATED = re.compile(r"^\s*//\s*<auto-generated", re.IGNORECASE)

_TYPE = re.compile(
    r"\b(?P<kind>record\s+struct|record\s+class|class|record|struct|interface|enum)\s+"
    r"(?P<name>[A-Za-z_]\w*)"
)
_NAMESPACE = re.compile(r"\bnamespace\b")
_ATTRIBUTES = re.compile(r"^\s*(?:\[[^\]]*\]\s*)+")
_IDENTIFIER_BEFORE_PAREN = re.compile(r"(?P<name>~?[A-Za-z_][\w.]*)\s*(?:<[^()]*>)?\s*$")
_LAST_IDENTIFIER = re.compile(r"(?P<name>[A-Za-z_][\w.]*)\s*$")
_CONTROLLER_BASE = re.compile(r"^(?:[\w]+\.)*(?:ControllerBase|Controller)$")
_TYPE_NAME = r"[A-Za-z_][\w.]*(?:<[^;{}()=]*>)?(?:\[\])*\??"
_LOCAL = re.compile(
    rf"(?:^|(?<=[;{{}}]))\s*(?:await\s+)?(?:using\s+)?(?P<type>{_TYPE_NAME})\s+"
    r"(?P<name>[A-Za-z_]\w*)\s*(?:=(?![=>])|;)"
)
_FOREACH = re.compile(rf"\bforeach\s*\(\s*(?:var|{_TYPE_NAME})\s+(?P<name>[A-Za-z_]\w*)\s+in\b")
_NOT_A_TYPE = frozenset(
    {
        "return",
        "throw",
        "else",
        "new",
        "await",
        "yield",
        "goto",
        "case",
        "const",
        "using",
        "in",
        "out",
        "ref",
        "is",
        "as",
        "not",
        "and",
        "or",
    }
)
_CODE_KINDS = frozenset({"method", "property", "block", "root"})


@dataclass
class _Scope:
    kind: str
    """namespace, type, enum, method, property, block (code) or data (not code)."""
    name: str | None = None
    type_kind: TypeKind | None = None


@dataclass
class CollectedFacts:
    types: list[TypeFact] = field(default_factory=list)
    properties: list[MemberFact] = field(default_factory=list)
    methods: list[MemberFact] = field(default_factory=list)
    locals: list[MemberFact] = field(default_factory=list)
    files: list[FileFact] = field(default_factory=list)


def extract_code_facts(working_copy: Path, project_folder: str) -> CodeFacts:
    """The names declared in the Web project's own `.cs` files."""
    collected = CollectedFacts()
    for source in source_files(working_copy / project_folder):
        relative = source.relative_to(working_copy).as_posix()
        if _skipped(relative):
            continue
        try:
            text = source.read_bytes().decode("utf-8")
        except UnicodeDecodeError:
            continue
        if _AUTO_GENERATED.match(text):
            continue
        file_types = len(collected.types)
        facts_in_source(text, relative, collected)
        collected.files.append(
            FileFact(
                file_path=relative,
                types=tuple(t.name for t in collected.types[file_types:]),
            )
        )
    return _bounded(collected)


def facts_in_source(
    text: str, file_path: str, into: CollectedFacts | None = None
) -> CollectedFacts:
    """Collect the declarations of one source file into `into` (a new collection if None)."""
    collected = into if into is not None else CollectedFacts()
    _FileReader(mask_source(text).text, file_path, collected).read()
    return collected


def _skipped(relative: str) -> bool:
    parts = relative.lower().split("/")
    return bool(EXCLUDED_FOLDERS & set(parts[:-1])) or parts[-1].endswith(GENERATED_SUFFIXES)


def _bounded(collected: CollectedFacts) -> CodeFacts:
    lists: dict[str, Sequence[object]] = {
        "types": collected.types,
        "properties": collected.properties,
        "methods": collected.methods,
        "locals": collected.locals,
        "files": collected.files,
    }
    truncated = tuple(name for name, items in lists.items() if len(items) > MAX_CODE_FACTS)
    return CodeFacts(
        types=tuple(collected.types[:MAX_CODE_FACTS]),
        properties=tuple(collected.properties[:MAX_CODE_FACTS]),
        methods=tuple(collected.methods[:MAX_CODE_FACTS]),
        locals=tuple(collected.locals[:MAX_CODE_FACTS]),
        files=tuple(collected.files[:MAX_CODE_FACTS]),
        truncated=truncated,
    )


class _FileReader:
    """One pass over a masked source, tracking scopes by braces."""

    def __init__(self, text: str, file_path: str, collected: CollectedFacts) -> None:
        self.text = text
        self.file_path = file_path
        self.collected = collected
        self.stack: list[_Scope] = []
        self.code_ranges: list[tuple[int, int]] = []
        self._newlines = [index for index, char in enumerate(text) if char == "\n"]

    def read(self) -> None:
        text = self.text
        header_start = 0
        code_start: int | None = 0  # the file root is code (top-level statements)
        for index, char in enumerate(text):
            if char not in "{};":
                continue
            if char == ";":
                self._statement(text[header_start:index], header_start)
                header_start = index + 1
                continue
            was_code = self._in_code()
            if char == "{":
                self.stack.append(self._open(text[header_start:index], header_start))
            elif self.stack:
                self.stack.pop()
            header_start = index + 1
            now_code = self._in_code()
            if was_code and not now_code and code_start is not None:
                self.code_ranges.append((code_start, index))
                code_start = None
            elif now_code and not was_code:
                code_start = index + 1
        if code_start is not None:
            self.code_ranges.append((code_start, len(text)))
        for start, end in self.code_ranges:
            self._locals(start, end)

    # ---------------------------------------------------------------- scopes

    def _in_code(self) -> bool:
        return not self.stack or self.stack[-1].kind in _CODE_KINDS

    def _type_name(self) -> str | None:
        return next((scope.name for scope in reversed(self.stack) if scope.kind == "type"), None)

    def _open(self, header: str, offset: int) -> _Scope:
        top = self.stack[-1].kind if self.stack else "root"
        if top in ("root", "namespace", "type"):
            declared = self._type_declaration(header, offset)
            if declared is not None:
                return declared
            if top != "type" and _NAMESPACE.search(header):
                return _Scope("namespace")
        if top == "type":
            return self._member_block(header, offset)
        if top in ("enum", "data"):
            return _Scope("data")
        return _Scope("block")

    def _type_declaration(self, header: str, offset: int) -> _Scope | None:
        match = _TYPE.search(header)
        if match is None:
            return None
        kind = TypeKind(match["kind"].split()[0])
        name = match["name"]
        bases = header[match.end() :].split(" where ", 1)[0]
        is_controller = ":" in bases and any(
            _CONTROLLER_BASE.match(base.strip().split("<", 1)[0])
            for base in bases.split(":", 1)[1].split(",")
        )
        self.collected.types.append(
            TypeFact(
                name=name,
                kind=kind,
                file_path=self.file_path,
                line=self._line(offset + match.start("name")),
                is_controller=is_controller,
            )
        )
        return _Scope("enum" if kind is TypeKind.ENUM else "type", name, kind)

    def _member_block(self, header: str, offset: int) -> _Scope:
        """A `{` directly inside a type: a method body, property accessors, or data."""
        clean = _strip_attributes(header)
        paren = clean.find("(")
        equals = clean.find("=")
        if paren >= 0 and (equals < 0 or equals > paren):
            self._method(clean, offset + (len(header) - len(clean)), paren)
            return _Scope("method")
        if equals < 0 and "this[" not in clean.replace(" ", ""):
            self._property(clean, offset + (len(header) - len(clean)))
            return _Scope("property")
        return _Scope("data")  # a field or collection initializer

    def _statement(self, statement: str, offset: int) -> None:
        """A `;`-terminated statement directly inside a type, a namespace or the root."""
        top = self.stack[-1].kind if self.stack else "root"
        if top in ("root", "namespace") and _TYPE.match(_strip_modifiers(statement)):
            self._type_declaration(statement, offset)  # record Point(int X, int Y);
            return
        if top != "type":
            return
        if _TYPE.match(_strip_modifiers(statement)):
            self._type_declaration(statement, offset)
            return
        clean = _strip_attributes(statement)
        start = offset + (len(statement) - len(clean))
        if "=>" in clean:
            left = clean.split("=>", 1)[0]
            paren = left.find("(")
            if paren >= 0 and "=" not in left[:paren]:
                self._method(left, start, paren)
            elif "=" not in left:
                self._property(left, start)
            return
        paren = clean.find("(")
        if paren >= 0 and "=" not in clean[:paren] and "delegate" not in clean.split():
            self._method(clean, start, paren)  # an abstract, interface or partial method

    # ---------------------------------------------------------------- members

    def _method(self, header: str, offset: int, paren: int) -> None:
        words = header[:paren].split()
        if "override" in words or "operator" in words or "delegate" in words:
            return
        match = _IDENTIFIER_BEFORE_PAREN.search(header[:paren])
        if match is None:
            return
        name = match["name"]
        type_name = self._type_name()
        explicit = "." in name or header[: match.start("name")].rstrip().endswith(".")
        if name.startswith("~") or explicit or name == type_name:
            return  # destructor, explicit interface implementation, constructor
        self.collected.methods.append(
            MemberFact(
                name=name,
                declaring_type=type_name,
                file_path=self.file_path,
                line=self._line(offset + match.start("name")),
            )
        )

    def _property(self, header: str, offset: int) -> None:
        words = header.split()
        type_scope = next((s for s in reversed(self.stack) if s.kind == "type"), None)
        in_interface = type_scope is not None and type_scope.type_kind is TypeKind.INTERFACE
        if "override" in words or not ("public" in words or in_interface):
            return
        match = _LAST_IDENTIFIER.search(header)
        if match is None or "." in match["name"] or len(words) < 2:
            return
        self.collected.properties.append(
            MemberFact(
                name=match["name"],
                declaring_type=self._type_name(),
                file_path=self.file_path,
                line=self._line(offset + match.start("name")),
            )
        )

    def _locals(self, start: int, end: int) -> None:
        segment = self.text[start:end]
        found: list[tuple[int, str]] = []
        for match in _LOCAL.finditer(segment):
            type_text = match["type"]
            if type_text in _NOT_A_TYPE or _preceded_by_const(segment, match.start("type")):
                continue
            found.append((match.start("name"), match["name"]))
        found += [(m.start("name"), m["name"]) for m in _FOREACH.finditer(segment)]
        for position, name in sorted(found):
            self.collected.locals.append(
                MemberFact(
                    name=name,
                    declaring_type=self._type_at(start + position),
                    file_path=self.file_path,
                    line=self._line(start + position),
                )
            )

    def _type_at(self, position: int) -> str | None:
        """The type enclosing `position`, found again by brace depth (locals are read later)."""
        stack: list[str | None] = []
        header_start = 0
        for index in range(position):
            char = self.text[index]
            if char == "{":
                match = _TYPE.search(self.text[header_start:index])
                stack.append(match["name"] if match else None)
                header_start = index + 1
            elif char == "}":
                if stack:
                    stack.pop()
                header_start = index + 1
            elif char == ";":
                header_start = index + 1
        return next((name for name in reversed(stack) if name is not None), None)

    def _line(self, position: int) -> int:
        return bisect.bisect_left(self._newlines, position) + 1


def _strip_attributes(header: str) -> str:
    """`header` without leading attributes and whitespace; the end is kept, so offsets
    computed from the length difference still point into the source."""
    return _ATTRIBUTES.sub("", header).lstrip()


def _strip_modifiers(statement: str) -> str:
    words = _strip_attributes(statement).split()
    modifiers = {
        "public",
        "private",
        "protected",
        "internal",
        "sealed",
        "abstract",
        "static",
        "partial",
        "readonly",
        "file",
        "unsafe",
        "new",
    }
    while words and words[0] in modifiers:
        words.pop(0)
    return " ".join(words)


def _preceded_by_const(segment: str, position: int) -> bool:
    before = segment[:position].rstrip()
    return before.endswith("const")
